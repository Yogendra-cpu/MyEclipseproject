package firstest;

public class Data_typeidentification {

	public static void main(String args[]) {
		
		byte a = 25;
	    int b =25000;
	    long c =  9876543210l;
	    float d = 12.5f;
	    double e = 99.999;
	    char f = 'A';
	    boolean g = true;
	    
	    System.out.println("byte value "+a);
	    System.out.println("integer value "+b);
	    System.out.println("long value "+c);
	    System.out.println("float value "+d);
	    System.out.println("double value "+e);
	    System.out.println("character value "+f);
	    System.out.println("boolean value "+g);
	}
	
}